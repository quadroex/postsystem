CREATE SCHEMA postal;
REVOKE ALL ON SCHEMA postal FROM PUBLIC;

CREATE TABLE postal.app_users (
    id uuid PRIMARY KEY,
    username text NOT NULL UNIQUE CHECK (btrim(username) <> ''),
    full_name text NOT NULL CHECK (btrim(full_name) <> ''),
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE postal.countries (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code char(2) NOT NULL UNIQUE,
    name text NOT NULL UNIQUE
);

CREATE TABLE postal.cities (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id integer NOT NULL REFERENCES postal.countries(id),
    name text NOT NULL,
    UNIQUE (country_id, name)
);

CREATE TABLE postal.addresses (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id integer NOT NULL REFERENCES postal.cities(id),
    street text NOT NULL CHECK (btrim(street) <> ''),
    building text NOT NULL CHECK (btrim(building) <> ''),
    postal_code text NOT NULL CHECK (postal_code ~ '^[0-9]{5}$'),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    created_by uuid NOT NULL REFERENCES postal.app_users(id),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_by uuid NOT NULL REFERENCES postal.app_users(id),
    deleted_at timestamptz,
    deleted_by uuid REFERENCES postal.app_users(id),
    CHECK ((deleted_at IS NULL) = (deleted_by IS NULL))
);

CREATE TABLE postal.branches (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL CHECK (btrim(name) <> ''),
    address_id integer NOT NULL REFERENCES postal.addresses(id),
    is_operational boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    created_by uuid NOT NULL REFERENCES postal.app_users(id),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_by uuid NOT NULL REFERENCES postal.app_users(id),
    deleted_at timestamptz,
    deleted_by uuid REFERENCES postal.app_users(id),
    CHECK ((deleted_at IS NULL) = (deleted_by IS NULL))
);

CREATE TABLE postal.customers (
    id uuid PRIMARY KEY,
    full_name text NOT NULL CHECK (btrim(full_name) <> ''),
    email text NOT NULL CHECK (
        email = lower(btrim(email))
        AND email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
    ),
    phone text NOT NULL CHECK (phone ~ '^\+?[0-9][0-9 ()-]{5,24}$'),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    created_by uuid NOT NULL REFERENCES postal.app_users(id),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_by uuid NOT NULL REFERENCES postal.app_users(id),
    deleted_at timestamptz,
    deleted_by uuid REFERENCES postal.app_users(id),
    CHECK ((deleted_at IS NULL) = (deleted_by IS NULL))
);

CREATE TABLE postal.service_types (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL,
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE postal.shipment_statuses (
    id integer PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL,
    is_terminal boolean NOT NULL DEFAULT false
);

CREATE TABLE postal.tariffs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_type_id integer NOT NULL UNIQUE REFERENCES postal.service_types(id),
    base_price numeric(12,2) NOT NULL CHECK (base_price >= 0),
    price_per_kg numeric(12,2) NOT NULL CHECK (price_per_kg >= 0),
    insurance_rate numeric(6,4) NOT NULL CHECK (insurance_rate BETWEEN 0 AND 1),
    max_weight_kg numeric(10,3) NOT NULL CHECK (max_weight_kg > 0)
);

CREATE TABLE postal.shipments (
    id uuid PRIMARY KEY,
    tracking_number text NOT NULL UNIQUE CHECK (tracking_number ~ '^[A-Z0-9]{8,32}$'),
    sender_id uuid NOT NULL REFERENCES postal.customers(id),
    recipient_id uuid NOT NULL REFERENCES postal.customers(id),
    origin_branch_id integer NOT NULL REFERENCES postal.branches(id),
    destination_branch_id integer NOT NULL REFERENCES postal.branches(id),
    service_type_id integer NOT NULL REFERENCES postal.service_types(id),
    status_id integer NOT NULL DEFAULT 1 REFERENCES postal.shipment_statuses(id),
    declared_value numeric(12,2) NOT NULL DEFAULT 0 CHECK (declared_value >= 0),
    price numeric(12,2) NOT NULL DEFAULT 0 CHECK (price >= 0),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    created_by uuid NOT NULL REFERENCES postal.app_users(id),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_by uuid NOT NULL REFERENCES postal.app_users(id),
    deleted_at timestamptz,
    deleted_by uuid REFERENCES postal.app_users(id),
    CHECK (origin_branch_id <> destination_branch_id),
    CHECK ((deleted_at IS NULL) = (deleted_by IS NULL))
);

CREATE TABLE postal.parcels (
    id uuid PRIMARY KEY,
    shipment_id uuid NOT NULL REFERENCES postal.shipments(id),
    description text NOT NULL CHECK (btrim(description) <> ''),
    weight_kg numeric(10,3) NOT NULL CHECK (weight_kg > 0),
    length_cm numeric(8,2) NOT NULL CHECK (length_cm > 0),
    width_cm numeric(8,2) NOT NULL CHECK (width_cm > 0),
    height_cm numeric(8,2) NOT NULL CHECK (height_cm > 0),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    created_by uuid NOT NULL REFERENCES postal.app_users(id)
);

CREATE TABLE postal.shipment_events (
    id uuid PRIMARY KEY,
    shipment_id uuid NOT NULL REFERENCES postal.shipments(id),
    status_id integer NOT NULL REFERENCES postal.shipment_statuses(id),
    branch_id integer NOT NULL REFERENCES postal.branches(id),
    note text NOT NULL DEFAULT '',
    occurred_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    recorded_by uuid NOT NULL REFERENCES postal.app_users(id)
);

CREATE TABLE postal.delivery_attempts (
    id uuid PRIMARY KEY,
    shipment_id uuid NOT NULL REFERENCES postal.shipments(id),
    branch_id integer NOT NULL REFERENCES postal.branches(id),
    attempt_no integer NOT NULL CHECK (attempt_no > 0),
    outcome text NOT NULL CHECK (outcome IN ('failed', 'delivered')),
    note text NOT NULL CHECK (btrim(note) <> ''),
    attempted_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    recorded_by uuid NOT NULL REFERENCES postal.app_users(id),
    UNIQUE (shipment_id, attempt_no)
);

CREATE TABLE postal.payment_methods (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL,
    requires_reference boolean NOT NULL DEFAULT false,
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE postal.payments (
    id uuid PRIMARY KEY,
    shipment_id uuid NOT NULL REFERENCES postal.shipments(id),
    amount numeric(12,2) NOT NULL CHECK (amount > 0),
    payment_method_id integer NOT NULL REFERENCES postal.payment_methods(id),
    reference text UNIQUE CHECK (reference IS NULL OR btrim(reference) <> ''),
    paid_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    recorded_by uuid NOT NULL REFERENCES postal.app_users(id)
);

CREATE TABLE postal.vehicles (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_number text NOT NULL UNIQUE,
    max_load_kg numeric(10,3) NOT NULL CHECK (max_load_kg > 0),
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE postal.transport_routes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE,
    origin_branch_id integer NOT NULL REFERENCES postal.branches(id),
    destination_branch_id integer NOT NULL REFERENCES postal.branches(id),
    CHECK (origin_branch_id <> destination_branch_id)
);

CREATE TABLE postal.route_stops (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id integer NOT NULL REFERENCES postal.transport_routes(id),
    branch_id integer NOT NULL REFERENCES postal.branches(id),
    stop_order integer NOT NULL CHECK (stop_order > 0),
    UNIQUE (route_id, stop_order),
    UNIQUE (route_id, branch_id)
);

CREATE TABLE postal.transport_runs (
    id uuid PRIMARY KEY,
    route_id integer NOT NULL REFERENCES postal.transport_routes(id),
    vehicle_id integer NOT NULL REFERENCES postal.vehicles(id),
    departure_at timestamptz NOT NULL,
    arrival_at timestamptz,
    status text NOT NULL DEFAULT 'planned' CHECK (status IN ('planned', 'in_transit', 'completed')),
    created_by uuid NOT NULL REFERENCES postal.app_users(id),
    CHECK (arrival_at IS NULL OR arrival_at > departure_at)
);

CREATE TABLE postal.run_shipments (
    run_id uuid NOT NULL REFERENCES postal.transport_runs(id),
    shipment_id uuid NOT NULL REFERENCES postal.shipments(id),
    loaded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    loaded_by uuid NOT NULL REFERENCES postal.app_users(id),
    PRIMARY KEY (run_id, shipment_id),
    UNIQUE (shipment_id)
);

CREATE TABLE postal.audit_log (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    entity_name text NOT NULL,
    entity_id text NOT NULL,
    operation text NOT NULL CHECK (operation IN ('insert', 'update', 'soft_delete', 'restore')),
    changed_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    changed_by uuid NOT NULL REFERENCES postal.app_users(id),
    old_data jsonb,
    new_data jsonb NOT NULL
);
